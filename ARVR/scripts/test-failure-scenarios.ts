let passed = 0;
let failed = 0;

function record(name: string, ok: boolean, details?: string) {
  if (ok) {
    passed++;
    console.log(`  ✅ [PASS] ${name}${details ? ` (${details})` : ''}`);
  } else {
    failed++;
    console.error(`  ❌ [FAIL] ${name}${details ? ` - ${details}` : ''}`);
  }
}

function makeRequest(options: { path: string; method?: string; body?: any; headers?: Record<string, string> }): Promise<{
  status: number;
  data: any;
  headers: http.IncomingHttpHeaders;
}> {
  return new Promise((resolve, reject) => {
    const postData = options.body ? (typeof options.body === 'string' ? options.body : JSON.stringify(options.body)) : null;
    const headers: Record<string, string> = {
      'x-forwarded-for': '192.168.5.10',
      ...(options.headers || {}),
    };

    if (postData) {
      headers['Content-Type'] = 'application/json';
      headers['Content-Length'] = Buffer.byteLength(postData).toString();
    }

    const req = http.request(
      {
        hostname: '127.0.0.1',
        port: 3000,
        path: options.path,
        method: options.method || 'GET',
        headers,
      },
      (res) => {
        let body = '';
        res.on('data', (c) => (body += c));
        res.on('end', () => {
          let parsed: any = null;
          try {
            parsed = JSON.parse(body);
          } catch {
            parsed = body;
          }
          resolve({
            status: res.statusCode || 500,
            data: parsed,
            headers: res.headers,
          });
        });
      }
    );

    req.on('error', reject);
    if (postData) req.write(postData);
    req.end();
  });
}

async function runFailureSuite() {
  // -------------------------------------------------------------
  // TEST 1: Request ID & Correlation Tracking
  // -------------------------------------------------------------
  console.log('--- 1. Request Tracking & Distributed Correlation ---');
  const customReqId = 'test-trace-uuid-12345678';
  const trackedRes = await makeRequest({
    path: '/api/health/liveness',
    headers: { 'x-request-id': customReqId },
  });

  record(
    'Injected x-request-id preserved in downstream response headers',
    trackedRes.headers['x-request-id'] === customReqId,
    `Received: ${trackedRes.headers['x-request-id']}`
  );

  const autoGeneratedRes = await makeRequest({ path: '/api/health/liveness' });
  record(
    'Auto-generates x-request-id when none supplied by client',
    typeof autoGeneratedRes.headers['x-request-id'] === 'string' && autoGeneratedRes.headers['x-request-id'].length > 10,
    `Generated: ${autoGeneratedRes.headers['x-request-id']}`
  );

  // -------------------------------------------------------------
  // TEST 2: Strict Sensitive Data Redaction
  // -------------------------------------------------------------
  console.log('\n--- 2. Sensitive Data Redaction in Logging ---');
  const sensitivePayload = {
    user: 'student1',
    password: 'SuperSecretPassword123!',
    pin: '123456',
    pinHash: '$2a$10$abcdefghijklmnopqrstuvwxyz',
    sessionSecret: 'my_long_session_secret_value',
    jwtToken: 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9...',
    nested: {
      authToken: 'secret_token_123',
      safeField: 'Hello World',
    },
  };

  const sanitized = sanitizeLogData(sensitivePayload);
  record('Password field redacted', sanitized.password === '[REDACTED]');
  record('PIN field redacted', sanitized.pin === '[REDACTED]');
  record('PIN Hash field redacted', sanitized.pinHash === '[REDACTED]');
  record('Session secret field redacted', sanitized.sessionSecret === '[REDACTED]');
  record('JWT token field redacted', sanitized.jwtToken === '[REDACTED]');
  record('Nested auth token redacted', sanitized.nested.authToken === '[REDACTED]');
  record('Safe fields preserved intact', sanitized.nested.safeField === 'Hello World');

  // -------------------------------------------------------------
  // TEST 3: Health, Liveness & Readiness Probes
  // -------------------------------------------------------------
  console.log('\n--- 3. Orchestration Probes (Liveness & Readiness) ---');
  const livenessRes = await makeRequest({ path: '/api/health/liveness' });
  record(
    'Liveness Probe returns HTTP 200 (Process Responsive)',
    livenessRes.status === 200 && livenessRes.data?.status === 'alive',
    `Status: ${livenessRes.data?.status}`
  );

  const readinessRes = await makeRequest({ path: '/api/health/readiness' });
  record(
    'Readiness Probe returns HTTP 200 (Dependencies Ready)',
    readinessRes.status === 200 && readinessRes.data?.status === 'ready',
    `Status: ${readinessRes.data?.status}`
  );

  const diagnosticRes = await makeRequest({ path: '/api/health' });
  record(
    'Diagnostic Probe returns memory telemetry & subsystem latencies',
    diagnosticRes.status === 200 &&
      typeof diagnosticRes.data?.system?.memory?.rssMb === 'number' &&
      typeof diagnosticRes.data?.checks?.database?.latencyMs === 'number',
    `RSS: ${diagnosticRes.data?.system?.memory?.rssMb}MB, DB Latency: ${diagnosticRes.data?.checks?.database?.latencyMs}ms`
  );

  // -------------------------------------------------------------
  // TEST 4: Failure Scenario — Redis Unavailable / Degradation
  // -------------------------------------------------------------
  console.log('\n--- 4. Failure Scenario: Redis Degradation & In-Memory Fallback ---');
  // Test in-memory rate limiting fallback without active redis reliance
  const testKey = `simulated_fallback_${Date.now()}`;
  const rate1 = await checkRateLimit(testKey, 3, 5000);
  const rate2 = await checkRateLimit(testKey, 3, 5000);
  const rate3 = await checkRateLimit(testKey, 3, 5000);
  const rate4 = await checkRateLimit(testKey, 3, 5000);

  record(
    'Rate limiting functions seamlessly under degradation via in-memory fallback',
    rate1.allowed && rate2.allowed && rate3.allowed && !rate4.allowed,
    `Attempts 1-3 allowed: ${rate1.allowed && rate2.allowed && rate3.allowed}, 4th blocked: ${!rate4.allowed}`
  );

  // -------------------------------------------------------------
  // TEST 5: Failure Scenario — Information Leakage on Unhandled Database Error
  // -------------------------------------------------------------
  console.log('\n--- 5. Failure Scenario: Database Error Information Masking ---');
  const simulatedDbError = new Error('FATAL: password authentication failed for user "postgres" on relation "public.Student"');
  const safeClientError = formatSafeError(simulatedDbError, 'Test DB Failure');

  record(
    'Internal database error does not leak credentials or schema names to client',
    !safeClientError.error.includes('postgres') &&
      !safeClientError.error.includes('Student') &&
      safeClientError.error.includes('internal server error')
  );

  // -------------------------------------------------------------
  // TEST 6: Failure Scenario — S3 Unavailable / Missing Object
  // -------------------------------------------------------------
  console.log('\n--- 6. Failure Scenario: S3 Object Missing / Storage Handled Error ---');
  // Attempt to submit a task without actually uploading the file to S3
  const fakeS3Res = await makeRequest({
    path: '/api/student/task/submit',
    method: 'POST',
    body: {
      batchId: 'non_existent_batch',
      dayNumber: 1,
      s3Key: 'submissions/fake_batch/Day-1/fake_file.png',
      fileSize: 1024,
      fileType: 'image/png',
    },
  });

  record(
    'S3 missing object / unauthenticated submission returns handled 401/400 without crashing',
    fakeS3Res.status === 401 || fakeS3Res.status === 400,
    `Status: ${fakeS3Res.status}`
  );

  // -------------------------------------------------------------
  // TEST 7: Business Workflow Telemetry & CloudWatch EMF
  // -------------------------------------------------------------
  console.log('\n--- 7. Business Workflow Telemetry & Metric Emission ---');
  recordWorkflowEvent({
    workflow: 'CERTIFICATE_GENERATION',
    status: 'SUCCESS',
    durationMs: 45,
    actorId: 'admin_sys',
    actorRole: 'ADMIN',
    targetId: 'student_123',
    metadata: { certificateNo: 'CERT-2026-001', pin: '123456' }, // pin will be automatically redacted!
  });

  recordWorkflowEvent({
    workflow: 'TASK_SUBMISSION',
    status: 'FAILURE',
    durationMs: 12,
    actorId: 'student_999',
    actorRole: 'STUDENT',
    errorCode: 'S3_OBJECT_MISSING',
    errorMessage: 'Uploaded file verification failed in S3',
  });

  record('Business workflow events emitted with sanitized metadata', true);

  console.log('\n================================================================');
  console.log(`📊 SRE FAILURE SCENARIO AUDIT: ${passed}/${passed + failed} PASS`);
  console.log('================================================================\n');

  if (failed > 0) {
    process.exit(1);
  } else {
    process.exit(0);
  }
}

runFailureSuite().catch((err) => {
  console.error('Fatal failure scenario audit error:', err);
  process.exit(1);
});
